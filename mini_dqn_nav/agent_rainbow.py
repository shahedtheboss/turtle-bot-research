import random
from collections import deque
import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
import torch.optim as optim

class NoisyLinear(nn.Module):

    #Factorized Gaussian NoisyNet layer as described in "Noisy Networks for Exploration" (Fortunato et al., 2017).
    def __init__(self, in_features, out_features, sigma0=0.5):
        """ 
        Generates noise for the weights and biases of the NoisyNet layer.
        The noise is factorized, meaning that the noise for each weight and bias is generated
        independently, but the same noise is used for all inputs to the layer.
        """
        super().__init__()

        self.in_features = in_features
        self.out_features = out_features


        self.weight_mu = nn.Parameter(torch.empty(out_features, in_features))
        self.weight_sigma = nn.Parameter(torch.empty(out_features, in_features))
        self.register_buffer("weight_epsilon", torch.empty(out_features, in_features))


        self.bias_mu = nn.Parameter(torch.empty(out_features))
        self.bias_sigma = nn.Parameter(torch.empty(out_features))
        self.register_buffer("bias_epsilon", torch.empty(out_features))


        bound = 1/np.sqrt(in_features)
        nn.init.uniform_(self.weight_mu, -bound, bound)
        nn.init.uniform_(self.bias_mu, -bound, bound)
        nn.init.constant_(self.weight_sigma, sigma0 / np.sqrt(in_features))
        nn.init.constant_(self.bias_sigma, sigma0 / np.sqrt(out_features))
        self.reset_noise()


    @staticmethod
    def _noise(size, device):
        # Generate noise from a standard normal distribution and apply a transformation to it.
        """ 
        Returns a factorized noise tensor of the specified size and device. 
        The noise is generated from a standard normal distribution and transformed to have a mean of 0 and a standard deviation of 1.
        The transformation is done by taking the sign of the noise and multiplying it by the square root
        of the absolute value of the noise. This ensures that the noise has a mean of 0 and a standard deviation of 1, which is important for the stability of the learning process.
        """
        x = torch.randn(size, device=device)
        return x.sign() * x.abs().sqrt()
    
    def reset_noise(self):
        """ 
        Resets the noise for the weights and biases of the NoisyNet layer. 
        This is done by generating new noise tensors for the weights and biases using the _noise method.
        The noise tensors are then used to perturb the weights and biases of the layer during training,
        which encourages exploration and helps prevent the agent from getting stuck in local optima.
        """
        x = self._noise(self.in_features, self.weight_mu.device)
        y = self._noise(self.out_features, self.weight_mu.device)
        self.weight_epsilon.copy_(y.outer(x))
        self.bias_epsilon.copy_(y)

    def forward(self, x):
        """ 
        Performs a forward pass through the NoisyNet layer.
        If the model is in training mode, the weights and biases are perturbed by the noise
        generated by the reset_noise method. If the model is in evaluation mode, the weights and biases are used as-is.
        The output of the layer is computed as a linear transformation of the input x using the pert
        urbed or unperturbed weights and biases, depending on the mode of the model.
        """
        if self.training:
            w = self.weight_mu + self.weight_sigma * self.weight_epsilon
            b = self.bias_mu + self.bias_sigma * self.bias_epsilon
        else:
            w, b  = self.weight_mu, self.bias_mu
        return F.linear(x,w,b)


class RainbowNetwork(nn.Module):
    """
    Rainbow DQN network architecture with NoisyNet and C51 distributional output.
    """

    def __init__(self, state_size, action_size, num_atoms=51, hidden=256):
        super().__init__()
        self.action_size = action_size
        self.num_atoms = num_atoms
        self.features = nn.Sequential(
            nn.Linear(state_size, hidden),
            nn.ReLU(),
            nn.Linear(hidden,hidden),
            nn.ReLU()
        )

        #Value Stream
        self.value_hidden = NoisyLinear(hidden, 128)
        self.value_out = NoisyLinear(128, num_atoms)

        #Advantage Stream
        self.adv_hidden = NoisyLinear(hidden, 128)
        self.adv_out = NoisyLinear(128, action_size* num_atoms)

    def forward(self, x):
        x = self.features(x)
        value = self.value_out(F.relu(self.value_hidden(x))).view(
            -1, 1, self.num_atoms
        )
        advantage = self.adv_out(F.relu(self.adv_hidden(x))).view(
            -1, self.action_size, self.num_atoms
        )
        return value + advantage - advantage.mean(dim=1, keepdim=True)

    def reset_noise(self):
        for layer in (self.value_hidden, self.value_out,
                      self.adv_hidden, self.adv_out):
            layer.reset_noise()


class PrioritizedNStepReplay:

    """
    Combines two techniques:

    1. Prioritized Experience Replay (PER):
       Experiences with higher priorities are sampled more frequently.

    2. N-step Learning:
       Combines rewards from multiple consecutive steps
       into a single experience.
    """

    def __init__(self,capacity, batch_size, n_step, gamma, alpha=0.6, beta_start=0.4,beta_frames = 1_000_000):

        # Maximum number of experiences the replay buffer can store.
        self.capacity, self.batch_size = capacity, batch_size      # Number of experiences to sample for each training update.

        # Number of consecutive rewards to combine (e.g. 3-step learning).
        self.n_step = n_step

        # Discount factor: determines how much future rewards are valued.
        self.gamma = gamma

        # Controls how strongly priorities affect sampling probabilities.
        # alpha = 0 means uniform sampling.
        # Larger alpha means stronger prioritization.
        self.alpha = alpha

        # Initial strength of importance-sampling bias correction.
        self.beta_start = beta_start

        # Number of sampling steps over which beta increases towards 1.
        self.beta_frames = beta_frames

        # Main replay memory: stores completed N-step experiences.
        self.memory = []

        # Stores the priority associated with each experience.
        # Initially, every priority is zero.
        self.priorities = np.zeros(capacity, dtype=np.float32)

        # Position where the next experience will be inserted.
        # Used to implement a circular replay buffer.
        self.position = 0

        # Temporary queue that collects recent experiences
        # until enough steps are available for N-step aggregation.
        self.queue = deque()

        # Counts how many batches have been sampled.
        # Used to gradually increase beta.
        self.samples = 0

        # Small positive value to prevent zero priorities.
        self.eps = 1e-6

    def __len__(self):
        """
        Returns the number of experiences currently stored
        in the main replay memory.
        """
        return len(self.memory)

    def _aggregate(self,seq):
        """
        Combines consecutive experiences into one N-step experience.

        Input:
            seq = [experience_1, experience_2, experience_3]

        Output:
            (initial_state,
             initial_action,
             accumulated_reward,
             final_next_state,
             final_done,
             actual_number_of_steps)
        """

        # Accumulator for discounted rewards.
        reward_sum = 0.0

        # Initially assume the final next state and done flag
        # come from the first experience.
        #experience_1 =
            #Index	Contents
            # [0]	State
            # [1]	Action
            # [2]	Reward
            # [3]	Next state
            # [4]	Done
        #[0][3] --> experience_1 , next_state
        last_next, last_done = seq[0][3], seq[0][4]

        # Tracks how many steps were actually aggregated.
        actual_n = 0

        # Go through each experience in the sequence.
        for i, item in enumerate(seq):
            """
             Add the current reward after discounting it.
            
             First reward:  gamma^0 * reward
             Second reward: gamma^1 * reward
             Third reward:  gamma^2 * reward
            
             Formula:
             R = r0 + gamma*r1 + gamma^2*r2 + ...

             itemp[2] = reward or the following experience
            """
            reward_sum += (self.gamma ** i) *item[2]

            # Update the final next state and done flag.
            # After the loop, these will represent the last
            # transition included in this N-step experience.
            last_next, last_done = item[3], item[4]

            # Count the number of transitions processed.
            actual_n = i + 1

             # If the episode ended, do not include any more steps.
            if last_done:
                break

        # The combined experience starts from the FIRST
        # experience's state and action.
        s, a = seq[0][0], seq[0][1]

        # Return the newly constructed N-step experience.
        return (s.copy(), 
                a, 
                reward_sum, 
                last_next.copy(), 
                last_done, 
                actual_n 
               )

    def _store(self, item):
        """
        Stores a completed N-step experience in the main memory.

        Assigns the new experience the maximum existing priority
        so that it has a reasonable chance of being sampled.
        """

        # If memory is not empty, find the highest existing priority.
        # If memory is empty, give the first experience priority 1.0.
        
        p = (
            float(self.priorities[:len(self.memory)].max())
            if self.memory else 1.0
        )

        # Safety check: priority must be positive and finite.
        if not np.isfinite(p) or p <= 0:
            p = 1.0


        # If memory has available space, append the new experience.
        if len(self.memory) < self.capacity:
            self.memory.append(item)

        # If memory is full, replace the oldest experience
        # at the current circular-buffer position.
        else:
            self.memory[self.position] = item

        self.priorities[self.position] = p
        # Move the position pointer forward in a circular manner.
        self.position = (self.position + 1) % self.capacity

    def add(self, state, action, reward, next_state, done, truncated=False):
        """
        Adds a new experience to the temporary queue.

        Once enough experiences are collected, they are aggregated
        into a single N-step experience and stored in the main memory.
        """

        # Append the new experience to the temporary queue.
        self.queue.append((
            np.asarray(state, dtype=np.float32).copy(), int(action),
            float(reward), np.asarray(next_state, dtype=np.float32).copy(),
            bool(done)
        ))

        # If enough experiences are collected for N-step aggregation:
        if done or truncated:
            
            while self.queue:
                # Aggregate the experiences and store them in main memory.
                self._store(self._aggregate(list(self.queue)[:self.n_step]))
                self.queue.popleft()  # Remove the oldest experience from the queue.
        elif len(self.queue) >= self.n_step:

            # Aggregate the first N experiences into one.
            self._store(self._aggregate(list(self.queue)[:self.n_step]))
            self.queue.popleft()  # Remove the oldest experience from the queue.

    def sample(self):
        size = len(self.memory)
        # If there are not enough experiences to sample a full batch, return None.
        if size < self.batch_size:
            return None
        # Scale the priorities by raising them to the power of alpha.
        scaled = self.priorities[:size] ** self.alpha
        # Normalize the scaled priorities to get probabilities.
        total = scaled.sum()
        # If the total is finite and positive, use it to normalize; otherwise, use uniform probabilities.
        probs = scaled/ total if np.isfinite(total) and total > 0 else np.full(size, 1/size)
        # Sample indices based on the computed probabilities.
        idx = np.random.choice(size, self.batch_size, replace=True, p = probs)
        # Compute importance-sampling weights to correct for the bias introduced by prioritized sampling.
        self.samples += 1
        # Gradually increase beta towards 1.0 over time to reduce bias.
        beta = min(1.0, self.beta_start + (1 - self.beta_start) * self.samples / self.beta_frames)
        # Compute the weights for the sampled experiences based on their probabilities and the current value of beta.
        weights = (size * probs[idx]) ** (-beta)
        # Normalize the weights to prevent excessively large updates.
        weights /= weights.max()
        # Return the sampled experiences, their indices, and the computed weights.
        batch = [self.memory[int(i)] for i in idx]
        return batch, idx, weights.astype(np.float32)

    def update_priorities(self, indices, values):
            """
            Updates the priorities of experiences based on their TD errors.
            """
            # Loop through the provided indices and corresponding TD error values.
            for i, value in zip(indices, values):
                # Ensure the priority is positive and finite.
                value = abs(float(value)) + self.eps
                # Update the priority for the experience at index i.
                self.priorities[int(i)] = value if np.isfinite(value) else 1.0


class RainbowDQNAgent:
    """
    Rainbow DQN for 52-dimensional observations and 7 discrete actions. 
    Includes Double DQN, Prioritized Experience Replay, 3-step learning, C51 and NoisyNet.
    """

    def __init__(self, state_size=52, action_size=7, learning_rate=1e-4,
                 gamma=0.99, batch_size=128, memory_size=50000, n_step=3,
                 num_atoms=51, v_min=-75.0, v_max=125.0,
                 target_update_every=250, warmup_transitions=1000):

        self.state_size, self.action_size = state_size,action_size
        self.gamma, self.batch_size = gamma, batch_size
        self.num_atoms, self.v_min, self.v_max = num_atoms, v_min, v_max
        self.target_update_every, self.warmup_transitions = target_update_every, warmup_transitions

        self.learning_steps = 0
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        self.support = torch.linspace(v_min, v_max, num_atoms, device = self.device) 
        self.delta_z =(v_max - v_min) / (num_atoms - 1)

        self.policy_net  = RainbowNetwork(
            state_size, action_size, num_atoms
        ).to(self.device)
        self.target_net = RainbowNetwork(
            state_size, action_size, num_atoms
        ).to(self.device)
        self.target_net.load_state_dict(self.policy_net.state_dict())
        self.target_net.train()    # NoisyNet noise is active during Bellman-target calculation.
        self.optimizer = optim.Adam(self.policy_net.parameters(), lr=learning_rate)
        self.memory = PrioritizedNStepReplay(
            memory_size, batch_size, n_step, gamma
        )

    def q_values(self, logits):
        """
        Converts logits to Q-values by computing the expected value
        of the distribution represented by the logits.
        """
        return (F.softmax(logits, dim=-1) * self.support.view(1, 1, -1)).sum(-1)

    def select_action(self, state):
        """
        Selects an action based on the current policy.
        The action with the highest Q-value is chosen.
        """
        #No epsilon-greedy: NoisyNet exploration is used instead.
        self.policy_net.train()
        self.policy_net.reset_noise()
        x = torch.as_tensor(state, dtype=torch.float32, device=self.device).unsqueeze(0)
        with torch.no_grad():
            return int(self.q_values(self.policy_net(x)).argmax(1).item())

    def select_greedy_action(self, state):
        self.policy_net.eval()  # deterministic mean weights for evaluation
        x = torch.as_tensor(state, dtype=torch.float32, device=self.device).unsqueeze(0)
        with torch.no_grad():
            action = int(self.q_values(self.policy_net(x)).argmax(1).item())
        self.policy_net.train()
        return action

    def remember(self, state, action, reward, next_state, done, truncated=False):
        self.memory.add(state, action, reward, next_state, done, truncated)

    def project(self, next_probs, rewards, dones, discounts):
        """
        Projects the distribution of the next state onto the support of the current state.
        This is part of the C51 algorithm for distributional reinforcement learning.
        """
        batch = rewards.size(0)
        tz = rewards[:, None] + discounts[:, None] * (1 - dones[:, None]) * self.support[None, :]
        tz = tz.clamp(self.v_min, self.v_max)
        b = (tz - self.v_min) / self.delta_z
        lower, upper = b.floor().long(), b.ceil().long()
        lower_w, upper_w = upper.float() - b, b - lower.float()
        equal = lower == upper
        lower_w = torch.where(equal, torch.ones_like(lower_w), lower_w)
        upper_w = torch.where(equal, torch.zeros_like(upper_w), upper_w)
        out = torch.zeros_like(next_probs)
        offsets = torch.arange(batch, device=self.device)[:, None] * self.num_atoms
        flat = out.view(-1)
        flat.index_add_(0, (lower + offsets).reshape(-1), (next_probs * lower_w).reshape(-1))
        flat.index_add_(0, (upper + offsets).reshape(-1), (next_probs * upper_w).reshape(-1))
        return out

    def learn(self):
        if len(self.memory) < max(self.batch_size, self.warmup_transitions):
            return None
        sampled = self.memory.sample()
        if sampled is None:
            return None
        batch, indices, weights = sampled
        states, actions, rewards, next_states, dones, n_steps = zip(*batch)

        states = torch.as_tensor(np.asarray(states), dtype=torch.float32, device=self.device)
        actions = torch.as_tensor(actions, dtype=torch.long, device=self.device)
        rewards = torch.as_tensor(rewards, dtype=torch.float32, device=self.device)
        next_states = torch.as_tensor(np.asarray(next_states), dtype=torch.float32, device=self.device)
        dones = torch.as_tensor(dones, dtype=torch.float32, device=self.device)
        n_steps = torch.as_tensor(n_steps, dtype=torch.float32, device=self.device)
        weights = torch.as_tensor(weights, dtype=torch.float32, device=self.device)
        discounts = torch.pow(torch.full_like(n_steps, self.gamma), n_steps)

        # Reset policy noise only after the no-grad next-state pass. Keep this
        # noise sample unchanged until backward() has consumed the current-state graph.
        self.policy_net.train()
        self.policy_net.reset_noise()
        logits = self.policy_net(states)
        chosen_logits = logits[torch.arange(self.batch_size, device=self.device), actions]

        # Double DQN: online net chooses action; target net supplies its distribution.
        with torch.no_grad():
            # Reset target noise only after the no-grad next-state pass. Keep this
            # noise sample unchanged until backward() has consumed the current-state graph.
            # self.policy_net.reset_noise()
            self.target_net.reset_noise()
            online_q = self.q_values(self.policy_net(next_states))
            next_actions = online_q.argmax(dim=1)
            target_probs = F.softmax(self.target_net(next_states), dim=-1)
            selected_probs = target_probs[
                torch.arange(self.batch_size, device=self.device), next_actions
            ]
            target_dist = self.project(selected_probs, rewards, dones, discounts)


        per_item_loss = -(target_dist * F.log_softmax(chosen_logits, dim=1)).sum(1)
        loss = (weights * per_item_loss).mean()

        self.optimizer.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(self.policy_net.parameters(), 10.0)
        self.optimizer.step()

        # Distributional cross-entropy is used as the PER priority signal.
        self.memory.update_priorities(indices, per_item_loss.detach().cpu().numpy())
        self.learning_steps += 1
        if self.learning_steps % self.target_update_every == 0:
            self.update_target()
        return float(loss.item())

    def update_target(self):
        self.target_net.load_state_dict(self.policy_net.state_dict())

    def save(self, path):
        torch.save({
            "policy_net": self.policy_net.state_dict(),
            "target_net": self.target_net.state_dict(),
            "optimizer": self.optimizer.state_dict(),
            "learning_steps": self.learning_steps,
            "state_size": self.state_size,
            "action_size": self.action_size,
            "num_atoms": self.num_atoms,
            "v_min": self.v_min,
            "v_max": self.v_max
        }, path)

    def load(self, path):
        checkpoint = torch.load(path, map_location=self.device, weights_only=True)
        self.policy_net.load_state_dict(checkpoint["policy_net"])
        self.target_net.load_state_dict(checkpoint["target_net"])
        if "optimizer" in checkpoint:
            self.optimizer.load_state_dict(checkpoint["optimizer"])
        self.learning_steps = checkpoint.get(
            "learning_steps", checkpoint.get("learn_steps", 0)
        )
        self.policy_net.train()
        self.target_net.train()
